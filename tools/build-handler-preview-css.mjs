// Regenerates mockups/handler-preview.css from the app's own <style> block, so
// the Handler preview is styled by exactly the stylesheet the app ships. Run
// it after changing app CSS; tests/conveyor-view.test.mjs fails if the two
// drift apart.
//   node tools/build-handler-preview-css.mjs
import { readFile, writeFile } from 'node:fs/promises';

export const HEADER = `/* GENERATED by tools/build-handler-preview-css.mjs from index.html.
   Do not hand-edit: the Handler preview must be styled by the same
   stylesheet the app ships, or the preview stops being evidence. */
`;

export function extractAppStyle(html) {
  const match = /<style>([\s\S]*?)<\/style>/.exec(html);
  if (!match) throw new Error('index.html has no <style> block');
  // index.html sits at the repository root and its url() paths are relative to
  // it; this stylesheet is served from mockups/, one level down, so the font
  // would 404. Nothing else about the CSS is changed.
  return match[1].replace(/url\((["']?)assets\//g, 'url($1../assets/');
}

export async function build(root = new URL('../', import.meta.url)) {
  const html = await readFile(new URL('index.html', root), 'utf8');
  const css = HEADER + extractAppStyle(html);
  await writeFile(new URL('mockups/handler-preview.css', root), css);
  return css.length;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  console.log(`handler-preview.css: ${await build()} bytes`);
}
